SELECT * FROM BOOK WHERE PUBLISHED_YEAR > 1950;

-- QUES-3 LIST ALL CUSTOMERS FROM THE CANANDA 
SELECT * FROM CUSTOMERS WHERE COUNTRY = "CANADA";

-- QUES-4 SHOW ORDERS PLACED IN NOVEMBER 2023
SELECT * FROM ORDERS WHERE ORDER_DATE BETWEEN '2023-11-1' AND '2023-11-30';

-- QUES-5 RETRIEVE THE TOTAL STOCK OF BOOKS AVAIABLE 
SELECT SUM (STOCK) AS TOTAL_STOCK FROM  BOOK ;

-- QUES-6 FIND THE DETAILS OF THE MOST EXPENSIVE BOOK  
