-- ADVANCED QUESTION 
-- QUES-12 RETRIEVE THE TOTAL NUMBER OF BOOKS SOLD FOR EACH GENRE 
SELECT 
    B.GENRE,
    SUM(O.QUANTITY) AS TOTAL_BOOKS_SOLD
FROM ORDERS O
JOIN BOOK B
    ON O.BOOK_ID = B.BOOK_ID
GROUP BY B.GENRE;

-- QUES-13 FIND THE AVERAGE PRICE OF BOOKS IN THE "FANTASY" GENRE 
SELECT AVG(PRICE)AS AVERAGE_PRICE 
FROM BOOK 
WHERE GENRE = "FANTASY";

-- QUES-14 LIST CUSTOMER WHO HAVE PLACED AT LEAST 2 ORDERS 
SELECT ORDERS.CUSTOMER_ID, CUSTOMERS.NAME, COUNT(ORDERS.ORDER_ID) AS ORDER_COUNT
FROM ORDERS 
JOIN CUSTOMERS ON ORDERS.CUSTOMER_ID = CUSTOMERS.CUSTOMER_ID
GROUP BY ORDERS.CUSTOMER_ID , CUSTOMERS.NAME
HAVING COUNT (ORDER_ID) >= 2;

-- QUES-15 FIND THE MOST FREQUENTLY ORDERED BOOK 
SELECT ORDERS.BOOK_ID, BOOK.TITLE , COUNT(ORDERS.ORDER_ID) AS ORDER_COUNT
FROM ORDERS 
JOIN BOOK ON ORDERS.BOOK_ID = BOOK.BOOK_ID 
GROUP BY ORDERS.BOOK_ID, BOOK.TITLE
ORDER BY ORDER_COUNT DESC LIMIT 1;

-- QUES-16 SHOW THE TOP 3 MOST EXPENSIVE BOOK "FANTASY" GENRE;
SELECT * FROM BOOK 
WHERE GENRE = "FANTASY" 
ORDER BY PRICE
DESC LIMIT 3;

-- QUES-17 RETRIEVING THE TOTAL QUANTITY OF BOOK SOLD BY EACH AUTHOR 
SELECT DISTINCT BOOK.AUTHOR , SUM(ORDERS.QUANTITY) AS TOTAL_QUANTITY
FROM ORDERS
JOIN BOOK ON ORDERS.BOOK_ID = BOOK.BOOK_ID 
GROUP BY BOOK.AUTHOR;

-- QUES-18 LIST THE CITIES WHERE CUSTOMERS WHO SPENT OVER $30 ARE LOCATED 
SELECT DISTINCT CUSTOMERS.CITY, TOTAL_AMOUNT
FROM ORDERS
JOIN CUSTOMERS ON CUSTOMERS.CUSTOMER_ID = ORDERS.CUSTOMER_ID 
WHERE ORDERS.TOTAL_AMOUNT > 30;

-- QUES-19 FIND THE CUSTOMER WHO SPEND THE MOST ON ORDERS 
SELECT CUSTOMERS.CUSTOMER_ID , CUSTOMERS.NAME, SUM(ORDERS.TOTAL_AMOUNT) AS TOTAL_SPEND 
FROM ORDERS 
JOIN CUSTOMERS ON ORDERS.CUSTOMER_ID = CUSTOMERS.CUSTOMER_ID 
GROUP BY CUSTOMERS.CUSTOMER_ID , CUSTOMERS.NAME 
ORDER BY TOTAL_SPEND DESC LIMIT 1;

-- QUES-20 CALCULATE THE STOCK REMAMINING AFTER FULFULLING ALL ORDERS
SELECT BOOK.BOOK_ID , BOOK.TITLE, BOOK.STOCK, coalesce(SUM(ORDERS.QUANTITY),0) AS ORDER_QUANTITY ,
 BOOK.STOCK-coalesce(SUM(ORDERS.QUANTITY),0) AS REMAINING_QUANTITY 
FROM BOOK
LEFT JOIN ORDERS ON BOOK.BOOK_ID = ORDERS.BOOK_ID 
GROUP BY BOOK.BOOK_ID ORDER BY BOOK.BOOK_ID;